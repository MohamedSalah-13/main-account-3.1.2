-- =====================================================================
-- V15: فصل الشِّق النقدي عن الشِّق الحسابي في المرتجعات الآجلة
-- =====================================================================
--
-- الخلفية. عمودا paid_from_treasury و paid_to_treasury يقولان باسمهما إنهما ما
-- تحرّكته الخزينة، وهذا ما تعنيه الفاتورة النقدية بهما فعلا. أما في المرتجع
-- **الآجل** فقد كان الـ views يقرآنهما بالمعنى المعاكس، وكل واحد منهما بطريقته:
--
--   account_customer_table:  purchase = IF(invoice_type = 1, total, 0)
--                            paid     = paid_from_treasury
--     أي أن الحساب يُخصم بمقدار paid_from_treasury - فالعمود عندها هو
--     "المخصوم من حساب الطرف"، لا المدفوع من الخزينة.
--
--   treasury_balance:        output = IF(invoice_type = 1, paid_from_treasury,
--                                        total - discount - paid_from_treasury)
--     أي أن الخزينة تصرف **الباقي** - وهو الشِّق الآخر تماما.
--
-- المعادلتان متسقتان معا تحت عُرف واحد غير مكتوب: في المرتجع الآجل،
-- paid_* = ما خُصم من حساب الطرف، والباقي هو النقدية. والبيانات الموجودة عند
-- العملاء أُدخلت على هذا العُرف - في قاعدة الاختبار كانت أرصدة ثلاثة موردين
-- تساوي 0.00 بالضبط بموجبه، بعد سنة ونصف من الدفعات.
--
-- R__views.sql صار يقرأ العمود بمعناه المعلن (نقدية)، فلا بد أن تنتقل البيانات
-- معه، وإلا قرأ الشِّق الحسابي على أنه نقدية وضخّم أرصدة الأطراف.
--
-- التحويل. تبديل الشِّقين، وهو حافظ للمعنى في كل الحالات:
--
--     paid_new = (total - discount) - paid_old
--
--   * paid_old = الصافي  (خصم كامل من الحساب)      -> paid_new = 0        (لا نقدية)
--   * paid_old = 0       (رد نقدي كامل)             -> paid_new = الصافي   (نقدية كاملة)
--   * ردّ جزئي                                      -> يتبادل الشِّقان بالضبط
--
-- المقصور على invoice_type = 2 عمدا. المرتجع النقدي يُخزَّن أصلا بـ
-- paid = الصافي، والمعادلتان القديمة والجديدة تعطيانه نفس الناتج، فتبديله
-- سيصفّر نقدية حقيقية.
--
-- انظر DocumentLedgerEffect (القاعدة مكتوبة مرة واحدة)،
-- ReturnCashSplitMigrationTest (يثبت نص هذا الملف)، و
-- PartyLedgerViewAcceptanceTest (يثبت اتفاق الـ views معها على قاعدة حقيقية).
-- =====================================================================

UPDATE total_sales_re
SET paid_from_treasury = total - discount - paid_from_treasury
WHERE invoice_type = 2;

UPDATE total_buy_re
SET paid_to_treasury = total - discount - paid_to_treasury
WHERE invoice_type = 2;
